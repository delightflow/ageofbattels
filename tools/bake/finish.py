"""After a bake: write assets/sprites/manifest.js (readable from file:// too) and a small icon sheet.

    python tools/bake/finish.py [assets/sprites]
"""
import json, os, sys, hashlib
from PIL import Image

D = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), '..', '..', 'assets', 'sprites'))
LOOKS = json.load(open(os.path.join(os.path.dirname(__file__), 'looks.json')))
man = json.load(open(os.path.join(D, 'manifest.json')))
# trim: every cell of a unit shares one tight box (the union over all its frames), which cuts memory several times over
for id, m in man.items():
    if m.get('cw'): continue
    W, H = m['w'] * m['ss'], m['h'] * m['ss']; cols, rows = len(m['frames']), m['dirs']
    c = Image.open(os.path.join(D, id + '.webp')).convert('RGBA'); k = Image.open(os.path.join(D, id + '_m.webp')).convert('RGBA')
    x0, y0, x1, y1 = W, H, 0, 0
    for r in range(rows):
        for q in range(cols):
            bb = c.crop((q * W, r * H, q * W + W, r * H + H)).split()[3].point(lambda v: 255 if v > 10 else 0).getbbox()
            if bb: x0, y0, x1, y1 = min(x0, bb[0]), min(y0, bb[1]), max(x1, bb[2]), max(y1, bb[3])
    if x1 <= x0: continue
    x0, y0 = max(0, x0 - 2) & ~1, max(0, y0 - 2) & ~1; x1, y1 = min(W, x1 + 2), min(H, y1 + 2); cw, ch = x1 - x0, y1 - y0
    for src, suf in ((c, '.webp'), (k, '_m.webp')):
        out = Image.new('RGBA', (cols * cw, rows * ch))
        for r in range(rows):
            for q in range(cols): out.paste(src.crop((q * W + x0, r * H + y0, q * W + x1, r * H + y1)), (q * cw, r * ch))
        out.save(os.path.join(D, id + suf), 'WEBP', quality=78, method=6, alpha_quality=80)
    m.update(cw=cw, ch=ch, ax=m['ax'] - x0 / m['ss'], ay=m['ay'] - y0 / m['ss'], w=cw / m['ss'], h=ch / m['ss'])
for id, m in man.items():                       # cache-busting version from the file contents
    h = hashlib.md5()
    for suf in ('.webp', '_m.webp'):
        p = os.path.join(D, id + suf)
        if os.path.exists(p): h.update(open(p, 'rb').read())
    m['v'] = h.hexdigest()[:8]

# icons: the standing frame facing down-left (buildings: their only view), trimmed and fitted into 64 px squares
S = 64; ids = [k for k in LOOKS if k in man]; cols = 8; rows = (len(ids) + cols - 1) // cols
ic = Image.new('RGBA', (cols * S, rows * S)); im = Image.new('RGBA', (cols * S, rows * S))
for n, id in enumerate(ids):
    m = man[id]; W, H = m['cw'], m['ch']; row = 0 if m['dirs'] == 1 else 1
    c = Image.open(os.path.join(D, id + '.webp')).convert('RGBA').crop((0, row * H, W, row * H + H))
    k = Image.open(os.path.join(D, id + '_m.webp')).convert('RGBA').crop((0, row * H, W, row * H + H))
    a = c.split()[3].point(lambda v: 255 if v > 150 else 0); bb = a.getbbox() or (0, 0, W, H)   # ignore the soft shadow
    x0, y0, x1, y1 = bb; side = max(x1 - x0, y1 - y0) + 6; cx, cy = (x0 + x1) // 2, (y0 + y1) // 2
    box = (cx - side // 2, cy - side // 2, cx - side // 2 + side, cy - side // 2 + side)
    for src, dst in ((c, ic), (k, im)): dst.paste(src.crop(box).resize((S, S), Image.LANCZOS), ((n % cols) * S, (n // cols) * S))
ic.save(os.path.join(D, 'icons.webp'), 'WEBP', quality=88, method=6); im.save(os.path.join(D, 'icons_m.webp'), 'WEBP', quality=88, method=6)
ver = hashlib.md5(open(os.path.join(D, 'icons.webp'), 'rb').read()).hexdigest()[:8]
man['__icons'] = {'size': S, 'cols': cols, 'ids': ids, 'v': ver}
json.dump({k: v for k, v in man.items() if k != '__icons'}, open(os.path.join(D, 'manifest.json'), 'w'), indent=0)
with open(os.path.join(D, 'manifest.js'), 'w') as f:
    f.write('/* generated by tools/bake/finish.py */\nglobalThis.AB_SPRITES = ' + json.dumps(man, separators=(',', ':')) + ';\n')
tot = sum(os.path.getsize(os.path.join(D, f)) for f in os.listdir(D) if f.endswith('.webp'))
print('manifest.js written: %d sprites, %.1f MB of webp' % (len(man) - 1, tot / 1e6))
